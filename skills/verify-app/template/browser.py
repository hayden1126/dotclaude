CACHE_GLOBS = (
    "~/.cache/puppeteer/chrome-headless-shell/*/chrome-headless-shell-*/chrome-headless-shell",
    "~/.cache/ms-playwright/chromium_headless_shell-*/chrome-headless-shell-*/chrome-headless-shell",
)
INSTALL_HINT = ("Install one with: npx @puppeteer/browsers install chrome-headless-shell@stable "
                "--path ~/.cache/puppeteer, or set VERIFY_CHROME to its path.")
CLICK_JS = """(() => {
  const el = document.querySelector(%s);
  if (!el || el.disabled) return null;
  el.scrollIntoView({block: "center", behavior: "instant"});
  const r = el.getBoundingClientRect();
  return r.width && r.height ? [r.x + r.width / 2, r.y + r.height / 2] : null;
})()"""
CLICK_TEXT_JS = """(() => {
  const text = %s;
  // innerText is undefined on an SVG element, which still has textContent.
  const squash = value => String(value ?? "").replace(/\\s+/g, " ").trim();
  const shown = [...document.querySelectorAll(%s)].filter(el => {
    const r = el.getBoundingClientRect();
    return r.width && r.height && getComputedStyle(el).visibility !== "hidden";
  });
  // Rendered text first, so the words of a hidden span never make a second match. The source text
  // only when no element renders the text: an SVG element, or a button under text-transform.
  let found = shown.filter(el => squash(el.innerText) === text);
  if (!found.length) found = shown.filter(el => squash(el.textContent) === text);
  if (found.length !== 1 || found[0].disabled) return {count: found.length, point: null};
  found[0].scrollIntoView({block: "center", behavior: "instant"});
  const r = found[0].getBoundingClientRect();
  return {count: 1, point: [r.x + r.width / 2, r.y + r.height / 2]};
})()"""


class BrowserError(Exception):
    """The browser died or could not start."""


class NoBrowser(BrowserError):
    """No usable browser binary."""


class PageError(Exception):
    """The page did not do what the journey needed."""


class JourneyError(Exception):
    """The journey is wrong whatever the page does. Not a PageError, so no poll waits it out."""


# Runs in the page with the result as this, and returns a plain copy of it for the by-value fetch.
# It throws, with UNRETURNABLE first in the message, on anything that fetch would mangle at any
# depth: a DOM node, the window or a Map comes back as {}, a function or symbol is dropped, a cycle
# is refused, and more than DEPTH_LIMIT arrays and objects nested in each other pass CDP's own
# limit. Only a plain object or an array, holding primitives or more of those, goes through. A plain
# object's prototype is Object.prototype, null, or another realm's Object.prototype (from an
# iframe's JSON.parse): one whose own prototype is null and whose constructor is named Object. It walks the value rather than
# trusting CDP's subtype: a NodeList can be labelled an array, and a reactive Proxy over a plain
# object (Vue, MobX) is labelled proxy. It returns the copy, not this, because CDP sends a Proxy by
# value as {}; and the copy holds exactly what the walk read, so a getter can't hand the fetch
# something else. It walks with plain index and key loops and takes the builtins it needs before
# reading the value, so a page that replaced Array.from or Array.prototype.map, or a getter that
# replaces Object.keys mid-walk, can't change what it checks. Known limit: a page that replaced
# Object.keys or Object.getPrototypeOf before the call still could.
UNRETURNABLE = "verify-unreturnable:"
# CDP's message encoder refuses a reply nested too deep ("CBOR: stack limit exceeded"). Measured on
# chrome-headless-shell, 297 arrays or objects nested in each other come back by value and 298 don't.
# The walk stops there, before the 20,000 levels that overflow its own stack.
DEPTH_LIMIT = 297
WALK_JS = """function () {
  "use strict";
  const protoOf = Object.getPrototypeOf, keysOf = Object.keys, isArray = Array.isArray;
  const own = Object.getOwnPropertyDescriptor, apply = Reflect.apply, create = Object.create;
  const objectProto = Object.prototype, tagOf = Object.prototype.toString;
  const open = [];  // the containers on the path to the value being walked
  const fail = (what, path) => { throw new Error(MARK + what + (path ? " at " + path : "")); };
  const named = proto => {
    const ctor = proto === null ? undefined : own(proto, "constructor");
    return ctor && typeof ctor.value === "function" ? String(ctor.value.name) : "";
  };
  const plain = value => {
    const proto = protoOf(value);
    return proto === objectProto || proto === null || (protoOf(proto) === null && named(proto) === "Object");
  };
  const walk = (value, path, depth) => {
    const kind = typeof value;
    if (value === null || kind === "undefined" || kind === "boolean" || kind === "number"
        || kind === "string") return value;
    if (kind !== "object") fail("a " + kind, path);
    for (let i = 0; i < open.length; i++) if (open[i] === value) fail("a cycle", path);
    if (depth >= LIMIT) fail("a value nested more than " + LIMIT + " levels deep", "");
    const array = isArray(value);
    if (!array && !plain(value)) {
      const tag = apply(tagOf, value, []);
      if (tag !== "[object Object]") fail("a " + tag.substring(8, tag.length - 1), path);
      const name = named(protoOf(value));
      fail((name ? "a " + name + " instance" : "an object with its own prototype") + ", not a plain object", path);
    }
    open[open.length] = value;
    let copy;
    if (array) {
      copy = [];
      for (let i = 0; i < value.length; i++) copy[i] = walk(value[i], path + "[" + i + "]", depth + 1);
    } else {
      copy = create(null);  // so a key named __proto__ stays a key
      const keys = keysOf(value);
      for (let i = 0; i < keys.length; i++) {
        copy[keys[i]] = walk(value[keys[i]], path + "." + keys[i], depth + 1);
      }
    }
    open.length -= 1;
    return copy;
  };
  return walk(this, "", 0);
}""".replace("MARK", json.dumps(UNRETURNABLE)).replace("LIMIT", str(DEPTH_LIMIT))


def thrown(details: dict) -> str:
    """What a page exception says, from CDP's exceptionDetails."""
    return details.get("exception", {}).get("description") or details.get("text") or "an exception"


def unreturnable(expression: str, kind: str) -> JourneyError:
    shown = expression if len(expression) <= 80 else expression[:77] + "..."
    return JourneyError(f"{shown!r} returned {kind}, which the browser can't send back as a value: "
                        "return a boolean, number or string from it instead (such as !!el or el.textContent), "
                        "or a plain array or object holding only those")


def find_browser() -> str:
    """Path of a chrome-headless-shell. Full Chrome aborts in a sandbox, so it is never a fallback."""
    configured = os.environ.get("VERIFY_CHROME")
    if configured:
        if os.access(configured, os.X_OK) and os.path.isfile(configured):
            return configured
        raise NoBrowser(f"VERIFY_CHROME={configured} is not an executable file. {INSTALL_HINT}")
    for pattern in CACHE_GLOBS:
        builds = glob.glob(os.path.expanduser(pattern))
        if builds:
            # Every run of digits, as ints: linux-131.0.6778.85 and chromium_headless_shell-1148
            return max(builds, key=lambda path: [int(n) for n in re.findall(r"\d+", pathlib.Path(path).parts[-3])])
    found = shutil.which("chrome-headless-shell")
    if found:
        return found
    raise NoBrowser(f"no chrome-headless-shell found. {INSTALL_HINT}")


class Browser:
    """One browser over --remote-debugging-pipe: fd 3 takes commands, fd 4 returns replies and
    events, each a JSON message ending in NUL. Every event is kept in self.events. Start it from
    the main thread with no other thread running: preexec_fn is only safe single-threaded.

    Any failure before it answers is a BrowserError, and it leaves no process or profile behind.
    timeout bounds each setup command, here and in Page."""

    def __init__(self, binary: str, out_dir: pathlib.Path, cwd: pathlib.Path, timeout: float = 30.0):
        self.out_dir, self.timeout = out_dir, timeout
        self.events = []
        self.claimed = set()  # downloads already handed to a journey
        downloads = out_dir / "downloads"
        downloads.mkdir(exist_ok=True)
        self.profile = tempfile.mkdtemp(prefix="verify-browser-")
        cmd_r, self._cmd_w = os.pipe()
        self._out_r, out_w = os.pipe()

        def wire():
            # Lift both ends above 3 and 4 first, so placing one cannot clobber the other. pass_fds
            # must name 3 and 4 themselves, or the child closes them before exec and hangs.
            a = fcntl.fcntl(cmd_r, fcntl.F_DUPFD, 10)
            b = fcntl.fcntl(out_w, fcntl.F_DUPFD, 10)
            os.dup2(a, 3)
            os.dup2(b, 4)

        args = [binary, "--no-sandbox", "--disable-gpu", "--disable-dev-shm-usage", "--no-first-run",
                "--no-default-browser-check", f"--user-data-dir={self.profile}", "--remote-debugging-pipe"]
        try:
            self.proc = subprocess.Popen(args, preexec_fn=wire, pass_fds=(3, 4), cwd=cwd,
                                         stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                                         stderr=subprocess.DEVNULL)
        except OSError as exc:
            shutil.rmtree(self.profile, ignore_errors=True)
            raise BrowserError(f"cannot start the browser {binary}: {exc}") from None
        finally:
            os.close(cmd_r)
            os.close(out_w)
        self._buf = b""
        self._ids = itertools.count(1)
        try:
            self.call("Browser.setDownloadBehavior",
                      {"behavior": "allow", "downloadPath": str(downloads), "eventsEnabled": True},
                      timeout=timeout)
        except BaseException as exc:  # an interrupt too: the caller never gets this object to close
            self.close(grace=2)
            if isinstance(exc, PageError):
                raise BrowserError(f"the browser did not set up: {exc}") from None
            raise

    def _next(self, deadline: float) -> dict | None:
        """The next message from the browser, or None at the deadline."""
        while b"\0" not in self._buf:
            left = deadline - time.monotonic()
            if left <= 0:
                return None
            if select.select([self._out_r], [], [], left)[0]:
                chunk = os.read(self._out_r, 1 << 20)
                if not chunk:
                    raise BrowserError("the browser process exited")
                self._buf += chunk
        raw, self._buf = self._buf.split(b"\0", 1)
        message = json.loads(raw)
        if message.get("method") == "Inspector.targetCrashed":
            raise BrowserError("the browser's render process crashed")
        if "method" in message:
            self.events.append(message)
        return message

    def pump(self, seconds: float):
        """Collect events for this long."""
        deadline = time.monotonic() + seconds
        while self._next(deadline):
            pass

    def call(self,
        method: str,
        params: dict | None = None,
        session: str | None = None,
        timeout: float = 30.0,
    ) -> dict:
        """Send one command and wait for its reply, keeping the events that arrive first."""
        mid = next(self._ids)
        message = {"id": mid, "method": method, "params": params or {}}
        if session:
            message["sessionId"] = session
        data = json.dumps(message).encode() + b"\0"
        try:
            while data:
                data = data[os.write(self._cmd_w, data):]
        except BrokenPipeError:
            raise BrowserError("the browser process exited") from None
        deadline = time.monotonic() + timeout
        while True:
            reply = self._next(deadline)
            if reply is None:
                raise PageError(f"{method} got no answer in {timeout}s: the page is stuck")
            if reply.get("id") != mid:
                continue
            if "error" in reply:
                raise PageError(f"{method}: {reply['error'].get('message', reply['error'])}")
            return reply.get("result", {})

    def close(self, grace: float = 5.0):
        """Ask the browser to quit, then kill only the process this run holds. Other sessions run
        Chrome on the same machine, so nothing here ever goes by name."""
        try:
            self.call("Browser.close", timeout=grace)
        except (BrowserError, PageError):
            pass
        try:
            self.proc.wait(timeout=grace)
        except subprocess.TimeoutExpired:
            self.proc.kill()
            self.proc.wait()
        os.close(self._cmd_w)
        os.close(self._out_r)
        shutil.rmtree(self.profile, ignore_errors=True)


class Page:
    """A tab attached in flat mode. Network records this tab only: a popup, a worker's own target
    or a request the server makes is not seen."""

    def __init__(self, browser: Browser, base: str):
        """Until the tab is ready the app has not been touched, so a failure here is a BrowserError."""
        self.browser, self.base = browser, base
        wait = browser.timeout
        try:
            self.target = browser.call("Target.createTarget", {"url": "about:blank"}, timeout=wait)["targetId"]
            self.session = browser.call("Target.attachToTarget", {"targetId": self.target, "flatten": True},
                                        timeout=wait)["sessionId"]
            for domain in ("Page", "Network", "Inspector"):
                self.call(f"{domain}.enable", timeout=wait)
            self.call("Emulation.setDeviceMetricsOverride",
                      {"width": 1440, "height": 1000, "deviceScaleFactor": 1, "mobile": False}, wait)
        except PageError as exc:
            raise BrowserError(f"the browser could not open a tab: {exc}") from None

    def call(self, method: str, params: dict | None = None, timeout: float = 30.0) -> dict:
        return self.browser.call(method, params, self.session, timeout)

    def goto(self, url: str, timeout: float = 30.0):
        """Open a path or URL and wait for it to load. net::ERR_ABORTED is a download, not a failure."""
        result = self.call("Page.navigate", {"url": urllib.parse.urljoin(self.base, url)}, timeout)
        if result.get("errorText", "net::ERR_ABORTED") != "net::ERR_ABORTED":
            raise PageError(f"{url}: {result['errorText']}")
        self.wait_for("document.readyState === 'complete'", timeout, f"{url} to load")

    def evaluate(self, expression: str):
        """The expression's value, awaited: a boolean, number, string or None, or a plain array or
        object holding only those, nested at most DEPTH_LIMIT deep. Anything else, at the top or
        nested (a DOM node, a function, a Map, a class instance, a cycle), is a JourneyError at
        once. Asked for by value, CDP sends a DOM node or a Map as {}, which reads as false at the
        top, so a wait_for on one would only time out, and nested it hides in a value that looks
        fine. So the result is kept by reference and WALK_JS checks it in the page before the
        by-value fetch."""
        result = self.call("Runtime.evaluate", {"expression": expression, "awaitPromise": True})
        if "exceptionDetails" in result:
            self.release_thrown(result)
            raise PageError(thrown(result["exceptionDetails"]))
        found = result["result"]
        if "objectId" not in found:  # a primitive, undefined or null: it came with its value
            return found.get("value")
        try:
            try:
                reply = self.call("Runtime.callFunctionOn", {"functionDeclaration": WALK_JS,
                                                             "objectId": found["objectId"], "returnByValue": True})
            except PageError as exc:  # a value the walk passed yet CDP refused; anything else (a navigation) stays a PageError
                if any(why in str(exc) for why in ("reference chain", "by value", "stack limit")):
                    raise unreturnable(expression, f"a {found.get('className') or 'object'}") from None
                raise
            if "exceptionDetails" in reply:
                self.release_thrown(reply)
                text = thrown(reply["exceptionDetails"])
                if UNRETURNABLE not in text:  # the page's own code threw, such as a getter
                    raise PageError(text)
                raise unreturnable(expression, text.split(UNRETURNABLE, 1)[1].splitlines()[0])
            return reply["result"].get("value")
        finally:
            self.release(found["objectId"])

    def release_thrown(self, reply: dict):
        """A reply that threw holds two handles to what was thrown: its result and its exception."""
        self.release(reply.get("result", {}).get("objectId"))
        self.release(reply["exceptionDetails"].get("exception", {}).get("objectId"))

    def release(self, object_id: str | None):
        """Drop a handle CDP keeps, for a result or a thrown exception, so a long wait_for doesn't
        pin one per poll for the tab's life. Best effort: a page that is gone took it along."""
        if object_id:
            try:
                self.call("Runtime.releaseObject", {"objectId": object_id})
            except PageError:
                pass

    def wait_for(self, expression: str, timeout: float = 30.0, what: str | None = None):
        """Poll until the expression is truthy and return its value."""
        deadline = time.monotonic() + timeout
        last = ""
        while True:
            try:
                value = self.evaluate(expression)
                if value:
                    return value
            except PageError as exc:  # a navigation can destroy the context mid-poll
                last = f" (last error: {exc})"
            if time.monotonic() >= deadline:
                raise PageError(f"timed out after {timeout}s waiting for {what or expression}{last}")
            time.sleep(0.1)

    def click(self, selector: str, timeout: float = 30.0):
        """A real mouse click on the element's centre, once it exists and is enabled."""
        self.press(*self.wait_for(CLICK_JS % json.dumps(selector), timeout, f"{selector} to be clickable"))

    def click_text(self, text: str, selector: str = "button, a, [role=button]", timeout: float = 30.0):
        """Click the one visible element matching selector whose text is exactly text, for a control
        with no id, ARIA label or data attribute. An element matches when text equals its rendered
        text (innerText, which applies CSS such as text-transform and leaves out a display: none
        span), with every whitespace run collapsed to one space and the ends trimmed, compared
        case-sensitively. Only when no element's rendered text matches does it fall back to the
        source text (textContent, collapsed the same way), which an SVG element has and innerText
        lacks. So a button showing a big "A" above a small "Single letter" is "A Single letter"; one
        whose source says "Export svg" under text-transform: uppercase matches "EXPORT SVG" and, by
        the fallback, "Export svg"; and "Save draft" picks the button showing that over one showing
        "Save" beside a hidden " draft". Zero matches, several, or one that stays disabled until the
        timeout is a PageError naming the count."""
        script = CLICK_TEXT_JS % (json.dumps(text), json.dumps(selector))
        deadline = time.monotonic() + timeout
        found, last = None, ""
        while True:
            try:
                found = self.evaluate(script)
            except PageError as exc:  # a navigation can destroy the context mid-poll
                last = f" (last error: {exc})"
            if found and found["point"]:
                return self.press(*found["point"])
            if time.monotonic() >= deadline:
                count = found["count"] if found else 0
                state = " and it is disabled" if count == 1 else ""
                raise PageError(f"{count} visible elements matching {selector!r} say {text!r}{state}: "
                                f"click_text needs exactly one enabled{last}")
            time.sleep(0.1)

    def press(self, x: float, y: float):
        """A left mouse press and release at a point in the viewport."""
        for kind in ("mousePressed", "mouseReleased"):
            self.call("Input.dispatchMouseEvent",
                      {"type": kind, "x": x, "y": y, "button": "left", "clickCount": 1})

    def fill(self, selector: str, text: str, timeout: float = 30.0):
        """Replace a field's text the way typing does."""
        self.click(selector, timeout)
        self.evaluate(f"document.querySelector({json.dumps(selector)}).select?.()")
        self.call("Input.insertText", {"text": text})

    def screenshot(self, name: str, timeout: float = 30.0) -> pathlib.Path:
        """Save <name>.png in the run's evidence folder and return its path. Anything in name outside
        letters, digits, dot, dash and underscore becomes _, so a JOURNEYS key like "a/b" is safe. A
        run folder deleted mid-run is made again, with its downloads folder."""
        shot = self.call("Page.captureScreenshot", {"format": "png"}, timeout)
        path = self.browser.out_dir / (re.sub(r"[^A-Za-z0-9._-]", "_", name) + ".png")
        (self.browser.out_dir / "downloads").mkdir(parents=True, exist_ok=True)
        path.write_bytes(base64.b64decode(shot["data"]))
        return path

    def download(self, timeout: float = 30.0) -> pathlib.Path:
        """Wait for the next finished download and return its file. A downloads folder deleted
        mid-run is made again first, for a download that starts after this call."""
        (self.browser.out_dir / "downloads").mkdir(parents=True, exist_ok=True)
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            names = {e["params"]["guid"]: e["params"]["suggestedFilename"] for e in self.browser.events
                     if e["method"] == "Browser.downloadWillBegin"}
            for event in self.browser.events:
                guid = event["params"].get("guid")
                if (event["method"] == "Browser.downloadProgress" and guid not in self.browser.claimed
                        and event["params"]["state"] == "completed"):
                    self.browser.claimed.add(guid)
                    return self.browser.out_dir / "downloads" / names[guid]
            self.browser.pump(0.1)
        raise PageError(f"no download finished in {timeout}s")

    def network(self) -> list:
        """Every request this tab made, in order: method, URL and status. A redirect keeps its
        requestId, so each hop gets its own row."""
        rows, latest = [], {}
        for event in self.browser.events:
            params = event["params"] if event.get("sessionId") == self.session else {}
            if event["method"] == "Network.requestWillBeSent" and params:
                latest[params["requestId"]] = {"method": params["request"]["method"],
                                               "url": params["request"]["url"], "status": None}
                rows.append(latest[params["requestId"]])
            elif event["method"] == "Network.responseReceived" and params.get("requestId") in latest:
                latest[params["requestId"]]["status"] = params["response"]["status"]
        return rows

    def close(self):
        self.browser.call("Target.closeTarget", {"targetId": self.target})
