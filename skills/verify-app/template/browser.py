"""A throwaway headless browser for verify.py, over a CDP pipe, stdlib only. A journey gets a Page
as ctx.page. Do not edit this file: journeys.py is the one an app changes.

PageError is the page misbehaving, so the journey fails (exit 1). BrowserError is the browser
failing, which says nothing about the app (exit 2): it died, or it never opened a ready tab.
JourneyError is the journey asking for something no page could give, such as an expression that
returns a DOM node: the journey is wrong, so the run can't judge the app (exit 2).
"""
